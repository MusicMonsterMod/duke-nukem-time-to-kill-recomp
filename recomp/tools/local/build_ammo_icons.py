#!/usr/bin/env python3
"""D08A32: write src/ttk/ammo_icons.h from assets/ui/ammo/ammo.json.

Each listed -15col.png frame (16x16 RGBA, alpha 0/255, at most 15 colours,
every channel exact in 5 bits) becomes a 4bpp cell and its palette, as the
D08A7 gadget cells: palette index 0 transparent, then the frame's colours in
raster order (PSX 15-bit, black as 0x8000 so it stays opaque); 16 rows of two
words, texel 0 in the lowest bits. Identical frames are stored once.

Usage: build_ammo_icons.py [--check]   (--check: fail if the header differs)
"""
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'assets/ui/ammo'
HEADER = ROOT / 'src/ttk/ammo_icons.h'
SLOTS = 30  # weapon records 0..29: slots 0..14 (+0x3ba) and the upgraded 27-29 (D08A40)


def cell(path):
    im = Image.open(path)
    if im.mode != 'RGBA' or im.size != (16, 16):
        raise SystemExit(f'{path.name}: need 16x16 RGBA, got {im.mode} {im.size}')
    palette, texels = [0], []
    for r, g, b, a in im.getdata():
        if not a:
            texels.append(0)
            continue
        if a != 255:
            raise SystemExit(f'{path.name}: alpha {a} (0 or 255 only)')
        if any(((c >> 3) << 3 | c >> 5) != c for c in (r, g, b)):
            raise SystemExit(f'{path.name}: colour {r},{g},{b} is not exact in 15-bit')
        colour = (r >> 3) | (g >> 3) << 5 | (b >> 3) << 10 or 0x8000
        if colour not in palette:
            palette.append(colour)
        texels.append(palette.index(colour))
    if len(palette) > 16:
        raise SystemExit(f'{path.name}: {len(palette) - 1} colours (15 at most)')
    palette += [0] * (16 - len(palette))
    words = []
    for y in range(16):
        for half in range(2):
            v = 0
            for i in range(8):
                v |= texels[16 * y + 8 * half + i] << (4 * i)
            words.append(v)
    return tuple(palette), tuple(words)


def build():
    manifest = json.loads((ASSETS / 'ammo.json').read_text())
    frames, index, first, count, names = [], {}, [-1] * SLOTS, [0] * SLOTS, [''] * SLOTS
    for w in manifest['weapons']:
        slot = w['slot']
        names[slot] = w['name']
        if not w['frames']:
            continue
        first[slot] = len(frames)
        count[slot] = len(w['frames'])
        for f in w['frames']:
            frames.append((f, cell(ASSETS / f)))
    unique, refs = [], []
    for f, c in frames:
        if c not in index:
            index[c] = len(unique)
            unique.append((f, c))
        refs.append(index[c])
    out = ['// Generated by tools/local/build_ammo_icons.py from assets/ui/ammo/ammo.json',
           '// (D08A32). Do not edit: change the PNGs and run the tool.',
           '#pragma once',
           '#include <cstdint>',
           'struct AmmoIconCell {uint16_t clut[16];uint32_t cell[32];};',
           f'static const AmmoIconCell k_ammo_cells[{len(unique)}]={{']
    for f, (pal, words) in unique:
        out.append(f'    {{  // {f}')
        out.append('     {' + ','.join(f'0x{v:04x}u' for v in pal) + '},')
        rows = [','.join(f'0x{v:08x}u' for v in words[i:i + 8]) for i in range(0, 32, 8)]
        out.append('     {' + (',\n      '.join(rows)) + '}},')
    out.append('};')
    out.append(f'// Frame n of weapon slot s is cell k_ammo_frames[k_ammo_first[s] + n].')
    out.append(f'static const uint8_t k_ammo_frames[{len(refs)}]={{' + ','.join(map(str, refs)) + '};')
    out.append(f'static const int16_t k_ammo_first[{SLOTS}]={{' + ','.join(map(str, first)) + '};')
    out.append(f'static const uint8_t k_ammo_count[{SLOTS}]={{' + ','.join(map(str, count)) + '};')
    out.append('// ' + ', '.join(f'{s} {n}' for s, n in enumerate(names) if n))
    return '\n'.join(out) + '\n'


def main():
    text = build()
    if '--check' in sys.argv[1:]:
        if not HEADER.exists() or HEADER.read_text() != text:
            print(f'{HEADER.relative_to(ROOT)} is out of date: run tools/local/build_ammo_icons.py')
            return 1
        print('ammo icons header up to date')
        return 0
    HEADER.write_text(text)
    print('wrote', HEADER.relative_to(ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
